#!/usr/bin/env node
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const read = p => fs.readFileSync(path.join(root,p),'utf8');
const source = read('src/app/presentation/system/system-scene-snapshot.ts');
const render = read('src/app/presentation/system/system-scene.ts');
const visual = read('src/app/presentation/system/system-scene-star-visual-profile-starvis1.ts');
const host = read('src/app/presentation/system/system-scene-host-visual-envelope.ts');
const clearance = read('src/app/presentation/system/system-scene-stellar-orbit-clearance.ts');
const multi = read('src/app/presentation/system/system-scene-multihost-composition.ts');
const tests = read('src/app/presentation/system/system-scene-star-visual-profile-starvis1.spec.ts');
let count = 0;
function check(label, fn) { fn(); count++; console.log('OK',label); }
check('estados científicos primario',()=>assert.match(source,/system\.primaryStar\.evolutionState\.name/));
check('estados científicos secundarios',()=>assert.match(source,/companion\.currentEvolutionState\.name/));
check('subtipos RGB\/AGB',()=>assert.match(source,/postMainSequenceStage\?\.name/));
check('espectro temperatura primaria',()=>assert.match(source,/primarySpectralAppearance\.spectralType\.family/));
check('espectro compañeros',()=>assert.match(source,/companion\.spectralAppearance\.spectralType\.family/));
check('perfiles centralizados',()=>assert.match(visual,/export function systemSceneStarvis1Profile/));
check('radios de enanas blancas',()=>assert.match(visual,/WHITE_DWARF: 0\.24/));
check('radios de gigantes',()=>assert.match(visual,/RGB: 3\.25, AGB: 4\.25, SUPERGIANT: 5\.2/));
check('remanentes compactos intactos',()=>assert.match(visual,/state === 'NEUTRON_STAR' \|\| state === 'STELLAR_BLACK_HOLE'/));
check('barrera final por periapsis proyectado',()=>assert.match(source,/planetPeriapsisScene: projectedNearestPlanetPeriapsisScene/));
check('cuerpo planetario en despeje',()=>assert.match(source,/planetRadiusScene: maxPlanetRadiusScene/));
check('barrera geométrica fail-closed',()=>assert.match(visual,/return Math\.min\(desired, Math\.max\(0, gap/));
check('limites V3 opt-in',()=>assert.match(host,/starvis1OptIn/));
check('limites V5 opt-in',()=>assert.match(clearance,/starvis1OptIn/));
check('múltiples conservan tamaño proporcionado',()=>assert.match(multi,/star\.radiusScene \* factor/));
check('caché por sistema de perfiles',()=>assert.match(source,/const starvisProfileById = new Map/));
check('sin físicas alteradas',()=>assert.doesNotMatch(visual,/IndexedDB|save\(|\.massSolar\s*=/));
check('coronas dependientes de familia',()=>assert.match(render,/starvisOpticalScale/));
check('sprite cap por órbita',()=>assert.match(render,/starvisOpticalBudgetScene/));
check('pick independiente',()=>assert.match(render,/systemScenePickingRadiusScene/));
check('prueba de gigante RGB',()=>assert.match(tests,/conserva su tamaño expandido/));
check('prueba de enana blanca',()=>assert.match(tests,/no vuelve a agrandar una enana blanca/));
check('test binario',()=>assert.match(tests,/V4 conserva el límite/));
console.log(`STARVIS.1 ${count}/${count} contratos comprobados`);
