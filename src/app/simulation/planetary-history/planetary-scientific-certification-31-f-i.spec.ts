import { afterEach, describe, expect, it, vi } from 'vitest';
import { DiscoveryState } from '../../domain/discovery/discovery-state';
import { BodyLocator } from '../../domain/generation/procedural-locator';
import { GeneratorVersion } from '../../domain/generation/generator-version';
import { UniverseGenerationKey } from '../../domain/generation/universe-generation-key';
import { UniverseSeed } from '../../domain/universe/universe-seed';
import { PlanetGenerator } from '../planetary/planet-generator';
import { AtmosphereGenerator } from '../planetary/atmosphere-generator';
import { MoonGenerator } from '../planetary/moon-generator';
import { HabitabilityPhysicalIntegration31Fb } from '../planetary/habitability-physical-integration-31-f-b';
import { PlanetScientificTargetResolver } from '../planetary/planet-scientific-target-resolver';
import { MoonScientificTargetResolver } from '../planetary/moon-scientific-target-resolver';
import { PlanetaryClimateGeochemistryHistoryResolver32_6 } from './planetary-climate-geochemistry-history-resolver-32-6';
import { PlanetaryEnvironmentalHistoryCertification31Fg } from './planetary-environmental-history-certification-31-f-g';
import { ObservedHabitabilityFiche31Fe } from '../../presentation/scientific/observed-habitability-fiche-31-f-e';

// The inputs below are generated by the real V1 19/20/21 engines, NOT copied
// into artificial atmospheric fixtures. V2 SINGLE/BINARY/TRIPLE/compact remain
// covered by their separate production session suites; this suite does NOT
// claim a complete V2 paleoclimate integration.
const source = new UniverseGenerationKey(
  UniverseSeed.parse('7F21-A9D4-18CE-4B70-92F1-6A0C-6E35-D8B1'), GeneratorVersion.V1,
);
const locator = (index: bigint) => new BodyLocator(3n, -17n, 8n, index);
const bodyKey = (index: bigint) => `G3/S-17/O8/B${index}`;

afterEach(() => vi.restoreAllMocks());

describe('31.F.i — certificación científica del límite entre producción real y cronología', () => {
  it('un planeta generado real alimenta 31.F.b y 32.6 sin convertir su atmósfera ACTUAL en historia', () => {
    const planets = vi.spyOn(PlanetGenerator, 'generate');
    const atmospheres = vi.spyOn(AtmosphereGenerator, 'generate');
    const moons = vi.spyOn(MoonGenerator, 'generate');
    const current = vi.spyOn(HabitabilityPhysicalIntegration31Fb, 'assessMaterialized');
    const target = PlanetScientificTargetResolver.resolveDetailed(source, locator(0n));
    expect(target).not.toBeNull();
    expect(planets).toHaveBeenCalledTimes(1);
    expect(atmospheres).toHaveBeenCalledTimes(1);
    expect(moons).toHaveBeenCalledTimes(1);
    expect(current).toHaveBeenCalledTimes(1);
    const actualAtmosphere = atmospheres.mock.results[0]!.value;
    expect(current.mock.calls[0]![1]).toBe(actualAtmosphere);
    expect(current.mock.calls[0]![0]).toBe(planets.mock.results[0]!.value);
    expect(current.mock.results[0]!.value.provenance).toBe('MATERIALIZED_19_20_21_CURRENT_CT0');
    const currentHistory = PlanetaryClimateGeochemistryHistoryResolver32_6.resolve({
      atmosphere: actualAtmosphere,
      // 19/20/21 provides no canonical dated system age at this handoff.
      // NULL is honest: no fabricated 4.6 Gyr epoch or extrapolation.
      time: { kind: 'CURRENT_SNAPSHOT', systemAgeBillionYears: null },
    });
    expect(currentHistory.bodyKey).toBe(bodyKey(0n));
    expect(currentHistory.snapshot.interpretation).toBe('CURRENT_PHYSICAL_STATE_NOT_HISTORICAL_TREND');
    expect(currentHistory.resolvedClimateGeochemistryChanges).toHaveLength(0);
    expect(currentHistory.chronology.episodes).toHaveLength(0);
    expect(currentHistory.chronology.presentYearAfterFormation).toBeNull();
    const certificate = new PlanetaryEnvironmentalHistoryCertification31Fg(currentHistory, 'actual-v1-present-31fi');
    expect(certificate.certification.certifiedContinuousIntervals).toBe(0);
    expect(certificate.certification.historicalCoverage).toBe('UNKNOWN');
    expect(certificate.certification.verdict).toBe('NO_CERTIFIED_ENVIRONMENTAL_TRAJECTORIES');
    const observed = ObservedHabitabilityFiche31Fe.planet(
      target!, DiscoveryState.CONFIRMED, true, bodyKey(0n), 'UNKNOWN',
    );
    expect(observed?.routes).toHaveLength(3);
    expect(observed?.note).toContain('no de continuidad histórica ni detección de vida');
    const serialized = JSON.stringify(observed);
    for (const forbidden of [
      'SIMULATED_REALITY', 'sourceRecordKey', 'sourceKey', 'physicalPotential',
      'lifeProbability', 'historicalContinuity', 'bodySeed',
    ]) expect(serialized).not.toContain(forbidden);
    // Neither 32.6 nor the 31.F.g certificate can regenerate any body.
    expect(planets).toHaveBeenCalledTimes(1);
    expect(atmospheres).toHaveBeenCalledTimes(1);
    expect(moons).toHaveBeenCalledTimes(1);
  }, 60_000);

  it('la luna V1 real queda separada del historial del planeta y del permiso de descubrimiento', () => {
    const planet = PlanetScientificTargetResolver.resolveDetailed(source, locator(6n));
    expect(planet).not.toBeNull();
    expect(planet!.detail.moons.relevantMoonCount).toBeGreaterThan(0);
    const target = MoonScientificTargetResolver.resolveDetailed(source, locator(6n), 0n);
    expect(target).not.toBeNull();
    const lunarKey = `${bodyKey(6n)}/M0`;
    const allowed = ObservedHabitabilityFiche31Fe.moon(
      target!, DiscoveryState.CONFIRMED, true, lunarKey, 'UNKNOWN',
    );
    expect(allowed?.routes).toHaveLength(3);
    expect(allowed?.routes[1].status).not.toBe('Océano confirmado');
    expect(allowed?.routes[2].status).toBe('Sin evidencia específica autorizada');
    expect(ObservedHabitabilityFiche31Fe.moon(
      target!, DiscoveryState.CATALOGUED, true, lunarKey, 'UNKNOWN',
    )).toBeNull();
    expect(ObservedHabitabilityFiche31Fe.moon(
      target!, DiscoveryState.CONFIRMED, false, lunarKey, 'UNKNOWN',
    )).toBeNull();
    expect(JSON.stringify(allowed)).not.toMatch(/sourceKey|SIMULATED_REALITY|lifeProbability|bodySeed/);
  }, 60_000);

  it('el límite de conocimiento no lee información privada aunque el sistema esté CONFIRMED', () => {
    const secret = new Proxy({}, { get: () => { throw new Error('private environmental data accessed'); } });
    expect(ObservedHabitabilityFiche31Fe.planet(
      secret as never, DiscoveryState.CONFIRMED, false, bodyKey(0n), 'SINGLE',
    )).toBeNull();
    expect(ObservedHabitabilityFiche31Fe.moon(
      secret as never, DiscoveryState.DISCOVERED, true, `${bodyKey(0n)}/M0`, 'BINARY',
    )).toBeNull();
  });
});
