/**
 * VISCIV.6d — The orbital host, not the brightest or nearest other star,
 * determines which hemisphere is the local day side for a civilization.
 * Pure presentation-only identity resolver; never persists additional data.
 */
export interface OrbitalHostLightPlanetV1 {
  readonly id: string;
  readonly orbitalHomeStarIds?: readonly string[];
}

export interface OrbitalHostLightStarV1 {
  readonly id: string;
  readonly label: string;
}

export function resolveOrbitalHomeStarIdsVISCIV6d(
  planet: OrbitalHostLightPlanetV1,
  stars: readonly OrbitalHostLightStarV1[],
): readonly string[] {
  const knownIds = new Set(stars.map(star => star.id));
  if (planet.orbitalHomeStarIds !== undefined) {
    const explicit = [...new Set(planet.orbitalHomeStarIds)].filter(id => knownIds.has(id));
    if (explicit.length > 0) return explicit;
  }

  // Compatibility for older presentation snapshots. New snapshots carry the
  // explicit identity generated by the native orbital hierarchy.
  const sTypeMatch = /^mh-([abc])-planet-/.exec(planet.id);
  if (sTypeMatch) {
    const label = sTypeMatch[1]!.toUpperCase();
    return stars.filter(star => star.label === label).map(star => star.id);
  }
  if (planet.id.startsWith('mh-p-planet-')) {
    return stars.filter(star => star.label === 'A' || star.label === 'B').map(star => star.id);
  }
  if (stars.length === 1) return [stars[0]!.id];

  // Legacy binaries/triples built from a single hierarchical planetary catalog
  // orbit the inner A-B pair rather than a randomly chosen luminous companion.
  const pair = stars.filter(star => star.label === 'A' || star.label === 'B');
  return pair.length > 0 ? pair.map(star => star.id) : [];
}

/** CPU mirror of shader's bounded visibility response, used for regression. */
export function civilizedLightsVisibilityVISCIV6d(
  dayFactors: readonly number[],
  weights: readonly number[],
  hostFlags: readonly boolean[],
): number {
  const bounded = (value: number) => Math.max(0, Math.min(1, value));
  const smoothstep = (a: number, b: number, x: number) => {
    const t = bounded((x - a) / (b - a));
    return t * t * (3 - 2 * t);
  };
  let totalDay = 0;
  let homeIncidence = 0;
  for (let i = 0; i < dayFactors.length; i += 1) {
    const day = bounded(dayFactors[i] ?? 0);
    totalDay += day * bounded(weights[i] ?? 0);
    if (hostFlags[i]) homeIncidence = Math.max(homeIncidence, day);
  }
  totalDay = bounded(totalDay);
  const deepNight = 1 - smoothstep(0.05, 0.16, totalDay);
  const weakStarlight = smoothstep(0.08, 0.22, totalDay);
  const homeDarkness = 1 - smoothstep(0.46, 0.54, homeIncidence);
  return bounded((deepNight + (1 - deepNight) * 0.22 * weakStarlight) * homeDarkness);
}
