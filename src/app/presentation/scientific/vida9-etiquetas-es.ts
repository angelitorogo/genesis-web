/** Los códigos desconocidos se muestran como códigos identificables, sin inventar una traducción. */
export function etiquetaVidaEs(codigo: string): string {
  return ES[codigo] ?? codigo.replaceAll('_',' ').toLocaleLowerCase('es-ES');
}
export function etiquetaNichoVidaEs(nicho: string): string {
  return nicho.split('/').map(etiquetaVidaEs).join(' / ');
}
